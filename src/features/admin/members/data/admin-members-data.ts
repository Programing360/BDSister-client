export function getAdminMemberById(idOrMemberId: string): AdminMemberDetail | undefined {
  if (!idOrMemberId) return undefined;
  const normalized = idOrMemberId.toLowerCase();
  return DEMO_ADMIN_MEMBERS.find(
    (m) =>
      m.id.toLowerCase() === normalized ||
      m.memberId.toLowerCase() === normalized
  );
}

