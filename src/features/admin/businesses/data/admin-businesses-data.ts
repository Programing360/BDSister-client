export const DEMO_BUSINESS_KPIS: BusinessKpiData = {
  totalBusinesses: DEMO_ADMIN_BUSINESSES.length,
  pendingApprovals: DEMO_ADMIN_BUSINESSES.filter((b) => b.status === "PENDING_REVIEW" || b.status === "UNDER_REVIEW").length,
  approvedBusinesses: DEMO_ADMIN_BUSINESSES.filter((b) => b.status === "APPROVED").length,
  rejectedBusinesses: DEMO_ADMIN_BUSINESSES.filter((b) => b.status === "REJECTED").length,
  suspendedBusinesses: DEMO_ADMIN_BUSINESSES.filter((b) => b.status === "SUSPENDED").length,
  verifiedBusinesses: DEMO_ADMIN_BUSINESSES.filter((b) => b.verificationStatus === "VERIFIED").length,
  totalProducts: DEMO_ADMIN_BUSINESSES.reduce((acc, b) => acc + b.productCount, 0),
  totalRevenueBDT: DEMO_ADMIN_BUSINESSES.reduce((acc, b) => acc + b.totalRevenueBDT, 0),
};

export function getAdminBusinessById(id: string): AdminBusinessItem | undefined {
  return DEMO_ADMIN_BUSINESSES.find((b) => b.id === id || b.slug === id || b.businessCode === id);
}

export function getAdminBusinessesByStatus(status?: BusinessApprovalStatus): AdminBusinessItem[] {
  if (!status) return [...DEMO_ADMIN_BUSINESSES];
  return DEMO_ADMIN_BUSINESSES.filter((b) => b.status === status);
}

export function getFeaturedBusinesses(): AdminBusinessItem[] {
  return DEMO_ADMIN_BUSINESSES
    .filter((b) => b.isFeatured)
    .sort((a, b) => (a.featuredOrder || 99) - (b.featuredOrder || 99));
}

export function calculateBusinessKpis(businesses: AdminBusinessItem[]): BusinessKpiData {
  return {
    totalBusinesses: businesses.length,
    pendingApprovals: businesses.filter((b) => b.status === "PENDING_REVIEW" || b.status === "UNDER_REVIEW").length,
    approvedBusinesses: businesses.filter((b) => b.status === "APPROVED").length,
    rejectedBusinesses: businesses.filter((b) => b.status === "REJECTED").length,
    suspendedBusinesses: businesses.filter((b) => b.status === "SUSPENDED").length,
    verifiedBusinesses: businesses.filter((b) => b.verificationStatus === "VERIFIED").length,
    totalProducts: businesses.reduce((acc, b) => acc + b.productCount, 0),
    totalRevenueBDT: businesses.reduce((acc, b) => acc + b.totalRevenueBDT, 0),
  };
}
