export function getAdminSellerById(id: string): AdminSellerItem | undefined {
  return DEMO_ADMIN_SELLERS.find((s) => s.id === id || s.sellerCode === id || s.memberId === id);
}

export function getAdminSellersByStatus(status?: SellerApprovalStatus): AdminSellerItem[] {
  if (!status) return [...DEMO_ADMIN_SELLERS];
  return DEMO_ADMIN_SELLERS.filter((s) => s.status === status);
}

export function calculateSellerKpis(sellers: AdminSellerItem[]): SellerKpiData {
  return {
    totalSellers: sellers.length,
    pendingSellers: sellers.filter((s) => s.status === "PENDING_APPROVAL" || s.status === "UNDER_REVIEW").length,
    approvedSellers: sellers.filter((s) => s.status === "APPROVED").length,
    suspendedSellers: sellers.filter((s) => s.status === "SUSPENDED").length,
    verifiedSellers: sellers.filter((s) => s.verificationStatus === "VERIFIED").length,
    totalMarketplaceRevenueBDT: sellers.reduce((acc, s) => acc + s.totalEarningsBDT, 0),
  };
}
