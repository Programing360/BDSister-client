export function getMembershipPlanById(id: string): MembershipPlan | undefined {
  return DEMO_MEMBERSHIP_PLANS.find((p) => p.id === id);
}

export function getSubscriptionById(id: string): MembershipSubscription | undefined {
  return DEMO_MEMBERSHIP_SUBSCRIPTIONS.find(
    (s) => s.id === id || s.subscriptionCode === id
  );
}

export function getRenewalReviewById(id: string): RenewalReviewItem | undefined {
  return DEMO_RENEWAL_REVIEWS.find((r) => r.id === id || r.subscriptionId === id);
}
